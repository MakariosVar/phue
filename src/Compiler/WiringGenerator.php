<?php

declare(strict_types=1);

namespace Phue\Compiler;

use ReflectionClass;
use ReflectionMethod;

/**
 * Static Build-Phase Wiring Generator for TypePHP AOT Compiler.
 *
 * Scans metadata/attributes and constructor signatures to emit zero-reflection
 * dependency and routing maps in PHP array and C++ struct formats.
 *
 * @package Phue\Compiler
 */
final class WiringGenerator
{
    /**
     * Initializes the wiring generator configuration.
     *
     * @param array<string> $scanDirectories Directories to scan for source classes.
     * @param string $outputDir Destination directory for generated wiring artifacts.
     */
    public function __construct(
        private readonly array $scanDirectories = ['src', 'app'],
        private readonly string $outputDir = 'build'
    ) {}

    /**
     * Generates both build/wiring.php and build/wiring.cpp static files.
     *
     * @return array{php_file: string, cpp_file: string, count: int} Map containing paths to emitted files and class count.
     */
    public function generate(): array
    {
        if (!is_dir($this->outputDir)) {
            mkdir($this->outputDir, 0777, true);
        }

        $discoveredClasses = $this->discoverClasses();
        $wiringData = [];

        foreach ($discoveredClasses as $className) {
            if (!class_exists($className)) {
                continue;
            }

            $reflector = new ReflectionClass($className);
            if ($reflector->isAbstract() || $reflector->isInterface()) {
                continue;
            }

            $constructor = $reflector->getConstructor();
            $dependencies = [];

            if ($constructor !== null) {
                foreach ($constructor->getParameters() as $param) {
                    $type = $param->getType();
                    $dependencies[] = [
                        'name' => $param->getName(),
                        'type' => $type instanceof \ReflectionNamedType ? $type->getName() : 'mixed',
                        'allows_null' => $param->allowsNull(),
                    ];
                }
            }

            $routes = [];
            foreach ($reflector->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                foreach ($method->getAttributes() as $attr) {
                    if (str_contains($attr->getName(), 'Route')) {
                        $routes[] = [
                            'method' => $method->getName(),
                            'args' => $attr->getArguments(),
                        ];
                    }
                }
            }

            $wiringData[$className] = [
                'dependencies' => $dependencies,
                'routes' => $routes,
            ];
        }

        $phpPath = $this->outputDir . '/wiring.php';
        $cppPath = $this->outputDir . '/wiring.cpp';

        $this->writePhpWiring($phpPath, $wiringData);
        $this->writeCppWiring($cppPath, $wiringData);

        return [
            'php_file' => $phpPath,
            'cpp_file' => $cppPath,
            'count' => count($wiringData),
        ];
    }

    /**
     * Scans configured directories recursively to extract Fully Qualified Class Names (FQCN).
     *
     * @return array<string> List of discovered fully qualified class names.
     */
    private function discoverClasses(): array
    {
        $classes = [];
        foreach ($this->scanDirectories as $dir) {
            if (!is_dir($dir)) {
                continue;
            }

            $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($dir));
            foreach ($iterator as $file) {
                if ($file->isFile() && $file->getExtension() === 'php') {
                    $content = file_get_contents($file->getPathname());
                    if ($content !== false &&
                        preg_match('/^\s*namespace\s+(.+?);/m', $content, $nsMatch) &&
                        preg_match('/^\s*(?:final\s+|abstract\s+)?class\s+([a-zA-Z0-9_]+)/m', $content, $classMatch)) {
                        $classes[] = $nsMatch[1] . '\\' . $classMatch[1];
                    }
                }
            }
        }
        return $classes;
    }

    /**
     * Serializes the wiring metadata array into an optimized PHP return file.
     *
     * @param string $path Target file path for the PHP wiring array.
     * @param array<string, mixed> $data Extracted dependency and route metadata.
     * @return void
     */
    private function writePhpWiring(string $path, array $data): void
    {
        $exported = var_export($data, true);
        $content = "<?php\n\ndeclare(strict_types=1);\n\n// Pre-compiled static wiring map generated by Phue TypePHP AOT Engine\nreturn {$exported};\n";
        file_put_contents($path, $content);
    }

    /**
     * Emits a C++ header/struct array containing static class wiring for native execution.
     *
     * @param string $path Target file path for the C++ wiring code.
     * @param array<string, mixed> $data Extracted dependency and route metadata.
     * @return void
     */
    private function writeCppWiring(string $path, array $data): void
    {
        $cppContent = "// Native C++ TypePHP AOT Pre-compiled Wiring Map\n";
        $cppContent .= "#include <unordered_map>\n#include <string>\n#include <vector>\n\n";
        $cppContent .= "namespace PhueAot {\n";
        $cppContent .= "    struct ClassWiring {\n";
        $cppContent .= "        const char* className;\n";
        $cppContent .= "        int dependencyCount;\n";
        $cppContent .= "    };\n\n";
        $cppContent .= "    static const ClassWiring STATIC_WIRING[] = {\n";

        foreach ($data as $class => $meta) {
            $depCount = count($meta['dependencies']);
            $escapedClass = addslashes($class);
            $cppContent .= "        {\"{$escapedClass}\", {$depCount}},\n";
        }

        $cppContent .= "    };\n}\n";
        file_put_contents($path, $cppContent);
    }
}